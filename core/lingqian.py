def draw(rng: random.Random | None = None) -> tuple[int, str, str, str]:
    """抽签：返回 (签号, 吉凶, 签诗, 解曰)。"""
    rng = rng or random.SystemRandom()
    index = rng.randrange(len(LINGQIAN))
    grade, poem, explain = LINGQIAN[index]
    return index + 1, grade, poem, explain


def build_result(question: str = "", sender: str = "") -> str:
    """生成求签结果文本。"""
    number, grade, poem, explain = draw()
    parts = ["🔮 观音灵签 · 求签"]
    if question:
        parts.append(f"所问之事：{question}")
    if sender:
        parts.append(f"求签人：{sender}")
    parts.append("")
    parts.append(f"第 {number} 签 · {grade}")
    parts.append("签诗：")
    parts.append(poem)
    parts.append("")
    parts.append(f"解曰：{explain}")
    parts.append("")
    parts.append("※ 灵签解读仅供参考娱乐，请理性看待。")
    return "\n".join(parts)
