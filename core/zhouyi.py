_YI_JING_SYMBOLS = "䷀䷁䷂䷃䷄䷅䷆䷇䷈䷉䷊䷋䷌䷍䷎䷏䷐䷑䷒䷓䷔䷕䷖䷗䷘䷙䷚䷛䷜䷝䷞䷟䷠䷡䷢䷣䷤䷥䷦䷧䷨䷩䷪䷫䷬䷭䷮䷯䷰䷱䷲䷳䷴䷵䷶䷷䷸䷹䷺䷻䷼䷽䷾䷿"


def hexagram_symbol(number: int) -> str:
    """六十四卦 Unicode 符号。"""
    if 1 <= number <= 64:
        return _YI_JING_SYMBOLS[number - 1]
    return ""


def toss_three_coins(rng: random.Random) -> int:
    """掷三枚铜钱，返回 6(老阴)/7(少阳)/8(少阴)/9(老阳)。"""
    backs = sum(1 for _ in range(3) if rng.random() < 0.5)
    return 6 + backs


def toss_hexagram(rng: random.Random | None = None) -> list[int]:
    """起卦：自下而上返回 6 爻（每爻为 6/7/8/9）。"""
    rng = rng or random.SystemRandom()
    return [toss_three_coins(rng) for _ in range(6)]


def _lines_to_trigram(lines: Iterable[int]) -> str:
    pattern = tuple(1 if v in (7, 9) else 0 for v in lines)
    return _TRIGRAM_BY_PATTERN[pattern]


def resolve_hexagram(lines: list[int]) -> tuple[int, str, str]:
    """由六爻（自下而上）解析出卦序号、上卦、下卦。"""
    lower = _lines_to_trigram(lines[:3])
    upper = _lines_to_trigram(lines[3:])
    number = HEX_GRID[upper][lower]
    return number, upper, lower


def changed_hexagram(lines: list[int]) -> tuple[int, list[int]]:
    """动爻变化后的卦：返回 (变卦序号, 变后的六爻)。"""
    new_lines = [9 if v == 6 else (6 if v == 9 else v) for v in lines]
    number, _, _ = resolve_hexagram(new_lines)
    return number, new_lines


_YAO_NAMES = {6: "老阴", 7: "少阳", 8: "少阴", 9: "老阳"}


def _yao_line(value: int) -> str:
    if value in (7, 9):
        base = "━━━━━"
    else:
        base = "━ ━ ━"
    mark = "○" if value == 9 else ("×" if value == 6 else "")
    return f"{base}{mark}"


def build_result(question: str = "", sender: str = "") -> str:
    """生成六爻占卜结果文本。"""
    lines = toss_hexagram()
    number, upper, lower = resolve_hexagram(lines)
    name, guaci, jie = HEXAGRAMS[number]
    moving = [i + 1 for i, v in enumerate(lines) if v in (6, 9)]

    parts = ["🔮 周易六爻 · 铜钱起卦"]
    if question:
        parts.append(f"所问之事：{question}")
    if sender:
        parts.append(f"求卦人：{sender}")
    parts.append("")
    parts.append(f"本卦：{hexagram_symbol(number)} {name}卦（{upper}{TRIGRAM_SYMBOLS[upper]}上，{lower}{TRIGRAM_SYMBOLS[lower]}下）")
    parts.append(f"卦辞：{guaci}")
    parts.append(f"简解：{jie}")
    parts.append("")
    parts.append("爻象（自下而上）：")
    for i, v in enumerate(lines, start=1):
        parts.append(f"第{i}爻 {_YAO_NAMES[v]} {_yao_line(v)}")

    if moving:
        dyn = "、".join(str(i) for i in moving)
        changed_number, _ = changed_hexagram(lines)
        cname, cguaci, cjie = HEXAGRAMS[changed_number]
        parts.append("")
        parts.append(f"动爻：第{dyn}爻（物极必反，事有变化之机）")
        parts.append(f"变卦：{hexagram_symbol(changed_number)} {cname}卦")
        parts.append(f"变卦卦辞：{cguaci}")
        parts.append(f"变卦简解：{cjie}")
    else:
        parts.append("")
        parts.append("六爻安静，暂无动象，宜守其常，静观其变。")
    parts.append("")
    parts.append("※ 周易占断仅供参考，重大决策请理性判断。")
    return "\n".join(parts)
